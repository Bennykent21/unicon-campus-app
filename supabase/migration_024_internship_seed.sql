       r.fields::text[], r.levels::text[], r.requirements, r.how_to_apply, r.apply_url, r.apply_email,
       r.status, r.opens_note, r.deadline, r.uniben_note, r.source_url, date '2026-10-24'
from rows r
join public.companies c on c.name = r.company
where not exists (
  select 1 from public.internships i
  where i.company_id = c.id and i.title = r.title
);
